#!/usr/bin/env python3
"""Generate the Latin-1 fallback fonts from the Montserrat source pinned with LVGL.

Pillow and FreeType are only needed to regenerate; the committed C files build without them.
Text is never normalized, transliterated or replaced.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path

import PIL
from PIL import Image, ImageDraw, ImageFont, features

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SOURCE = REPO_ROOT / "managed_components/lvgl__lvgl/scripts/built_in_font/Montserrat-Medium.ttf"
OUTPUT_DIR = REPO_ROOT / "components/ui/src/fonts"

FONT_SHA256 = "421f26b23e2be6b98373d32acd3cb2897b154d4bf0a77d26534ce476e4cbed53"
PILLOW_VERSION = "11.3.0"
FREETYPE_VERSION = "2.13.3"
CHARACTERS = "".join(map(chr, range(0xA0, 0x100)))
NO_BREAK_SPACE = 0xA0

# Line height and baseline of the matching built-in LVGL Montserrat font.
FONT_METRICS = {20: (22, 4), 24: (27, 5), 28: (30, 5)}

CANVAS_SIZE = 64
CANVAS_ORIGIN_X = 16
CANVAS_BASELINE_Y = 32
QUANTIZATION_STEP_4BPP = 17  # 255 / 15: 16 gray levels
ADVANCE_SCALE = 16
BITMAP_BYTES_PER_ROW = 12


def quantize_to_4bpp(value: int) -> int:
    return ((value + QUANTIZATION_STEP_4BPP // 2) // QUANTIZATION_STEP_4BPP) * QUANTIZATION_STEP_4BPP


def render_glyphs(font: ImageFont.FreeTypeFont, line_height: int, base_line: int) -> tuple[bytearray, list[dict]]:
    bitmaps = bytearray()
    glyphs = []
    for codepoint in map(ord, CHARACTERS):
        advance = round(font.getlength(chr(codepoint)) * ADVANCE_SCALE)
        canvas = Image.new("L", (CANVAS_SIZE, CANVAS_SIZE))
        ImageDraw.Draw(canvas).text((CANVAS_ORIGIN_X, CANVAS_BASELINE_Y), chr(codepoint), font=font, fill=255, anchor="ls")
        canvas = canvas.point(quantize_to_4bpp)
        bounds = canvas.getbbox()
        if not bounds:
            if codepoint != NO_BREAK_SPACE:
                raise ValueError(f"Missing glyph U+{codepoint:04X}")
            glyphs.append(dict(codepoint=codepoint, bitmap_index=len(bitmaps), adv_w=advance,
                               box_w=0, box_h=0, ofs_x=0, ofs_y=0))
            continue

        left, top, right, bottom = bounds
        width, height = right - left, bottom - top
        top -= CANVAS_BASELINE_Y
        bottom -= CANVAS_BASELINE_Y
        # Shift a glyph vertically, never crop or scale it, so it fits the LVGL line box.
        shift_y = max(0, -(line_height - base_line) - top)
        if bottom + shift_y > base_line:
            shift_y = base_line - bottom
        if top + shift_y < -(line_height - base_line) or bottom + shift_y > base_line:
            raise ValueError(f"Glyph U+{codepoint:04X} exceeds the line box")

        start = len(bitmaps)
        pixels = [value // QUANTIZATION_STEP_4BPP for value in canvas.crop(bounds).getdata()]
        for i in range(0, len(pixels), 2):
            low = pixels[i + 1] if i + 1 < len(pixels) else 0
            bitmaps.append((pixels[i] << 4) | low)
        glyphs.append(dict(codepoint=codepoint, bitmap_index=start, adv_w=advance, box_w=width, box_h=height,
                           ofs_x=left - CANVAS_ORIGIN_X, ofs_y=-(bottom + shift_y)))
    return bitmaps, glyphs


def generate(source: Path, size: int) -> tuple[str, int]:
    if hashlib.sha256(source.read_bytes()).hexdigest() != FONT_SHA256:
        raise ValueError("Font source hash differs; review the new source before regenerating")
    if PIL.__version__ != PILLOW_VERSION or features.version_module("freetype2") != FREETYPE_VERSION:
        raise ValueError("Renderer version differs; review the generated glyphs before changing the pins")

    line_height, base_line = FONT_METRICS[size]
    font = ImageFont.truetype(str(source), size, layout_engine=ImageFont.Layout.BASIC)
    bitmaps, glyphs = render_glyphs(font, line_height, base_line)

    rows = "\n".join("    " + ", ".join(f"0x{b:02x}" for b in bitmaps[i:i + BITMAP_BYTES_PER_ROW]) + ","
                     for i in range(0, len(bitmaps), BITMAP_BYTES_PER_ROW))
    fields = ["bitmap_index", "adv_w", "box_w", "box_h", "ofs_x", "ofs_y"]
    descriptions = "\n".join(["    {0}, /* Reserved missing glyph */"] + [
        f"    {{{', '.join(f'.{key} = {glyph[key]}' for key in fields)}}}, /* U+{glyph['codepoint']:04X} */"
        for glyph in glyphs])
    first = glyphs[0]["codepoint"]
    offsets = ", ".join(str(glyph["codepoint"] - first) for glyph in glyphs)

    code = f'''/* Generated by tools/generate_fonts.py; do not edit.
 * Latin-1 fallback (U+00A0-U+00FF), Montserrat Medium 7.200, {size} px, 4 bpp.
 * Copyright 2011 The Montserrat Project Authors. SIL OFL 1.1, see LICENSES/OFL-1.1-Montserrat.txt.
 * Source SHA-256: {FONT_SHA256}
 * Renderer: Pillow {PILLOW_VERSION}, FreeType {FREETYPE_VERSION}, basic layout.
 */
#include "ui_fonts.h"

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{
{rows}
}};

static const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {{
{descriptions}
}};

static const uint16_t unicode_list[] = {{{offsets}}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{{{
    .range_start = {first}, .range_length = {glyphs[-1]["codepoint"] - first + 1},
    .glyph_id_start = 1, .unicode_list = unicode_list,
    .glyph_id_ofs_list = NULL, .list_length = {len(glyphs)},
    .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY,
}}}};

static const lv_font_fmt_txt_dsc_t font_dsc = {{
    .glyph_bitmap = glyph_bitmap, .glyph_dsc = glyph_dsc, .cmaps = cmaps,
    .kern_dsc = NULL, .kern_scale = 0, .cmap_num = 1, .bpp = 4,
    .kern_classes = 0, .bitmap_format = LV_FONT_FMT_TXT_PLAIN,
}};

const lv_font_t ui_font_latin1_{size} = {{
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {line_height}, .base_line = {base_line}, .subpx = LV_FONT_SUBPX_NONE,
    .underline_position = -1, .underline_thickness = 1,
    .dsc = &font_dsc, .fallback = NULL,
}};
'''
    return code, len(bitmaps)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    parser.add_argument("--check", action="store_true", help="compare with the committed files without writing")
    args = parser.parse_args()

    for size in FONT_METRICS:
        output = OUTPUT_DIR / f"ui_font_latin1_{size}.c"
        code, bitmap_bytes = generate(args.source, size)
        if args.check:
            if not output.exists() or output.read_text() != code:
                raise SystemExit(f"{output.name} differs from the generated font")
        else:
            output.write_text(code)
        print(f"{output.name}: {len(CHARACTERS)} glyphs, {bitmap_bytes} bitmap bytes")


if __name__ == "__main__":
    main()
